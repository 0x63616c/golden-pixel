/// Compact numbers for a narrow HUD: 999, 1.2K, 12K, 123K, 1.2M ... then 1E36.
public func compact(_ v: Double) -> String {
    if !v.isFinite { return "MAX" }
    let n = max(0, v)
    if n < 1000 { return String(Int(n.rounded(.down))) }
    let suffixes = ["K", "M", "B", "T", "QA", "QI", "SX", "SP", "OC", "NO", "DC"]
    var x = n, i = -1
    while x >= 1000 && i < suffixes.count - 1 { x /= 1000; i += 1 }
    if x >= 1000 {
        let e = Int(log10(n).rounded(.down))
        return "1E\(e)"
    }
    if x < 10 {
        let t = (x * 10).rounded(.down) / 10
        let whole = Int(t), tenth = Int(((t - Double(whole)) * 10).rounded())
        return tenth == 0 ? "\(whole)\(suffixes[i])" : "\(whole).\(tenth)\(suffixes[i])"
    }
    return "\(Int(x.rounded(.down)))\(suffixes[i])"
}

